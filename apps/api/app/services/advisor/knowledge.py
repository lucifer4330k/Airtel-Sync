@lru_cache
def city_tiers() -> dict[str, int]:
    tiers = dict(EXTRA_CITIES)
    with (get_settings().data_dir / "smb_leads.csv").open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            tiers[row["city"].lower()] = int(row["city_tier"])
    return tiers


